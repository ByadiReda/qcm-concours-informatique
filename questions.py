def _generated_questions_for_category(category):
    topics = TOPIC_BANKS[category]
    _validate_topic_bank(category, topics)
    return _basic_questions(category, topics) + _intermediate_questions(category, topics) + _advanced_questions(category, topics[:16])


def build_questions():
    questions = list(SEED_QUESTIONS)
    for category in CATEGORY_ORDER:
        questions.extend(_generated_questions_for_category(category))
    return questions


QUESTIONS = build_questions()

EXPECTED_TOTAL = len(CATEGORY_ORDER) * sum(DIFFICULTY_TARGETS.values())

if len(QUESTIONS) != EXPECTED_TOTAL:
    raise ValueError(f"Le jeu de questions doit contenir exactement {EXPECTED_TOTAL} QCM.")

category_counts = Counter(question["category"] for question in QUESTIONS)
difficulty_counts = Counter(question["difficulty"] for question in QUESTIONS)
pairs = Counter((question["category"], question["difficulty"]) for question in QUESTIONS)

expected_categories = set(CATEGORY_ORDER)
expected_difficulties = set(DIFFICULTY_ORDER)

if set(category_counts) != expected_categories:
    raise ValueError(
        f"Les catégories doivent correspondre exactement à l'ensemble attendu. "
        f"Obtenu={sorted(category_counts)}, attendu={sorted(expected_categories)}"
    )
