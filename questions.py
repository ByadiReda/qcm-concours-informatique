def _validate_topic_bank(category, topics):
    if len(topics) < 16:
        raise ValueError(
            f"La banque de thèmes de {category} doit contenir au moins 16 entrées pour générer les volumes attendus."
        )


def _sentence(text):
    text = text.strip()
    if not text.endswith((".", "?", "!")):
        text += "."
    return text


def _pick(pool, current_index, getter, offset=1, count=3):
    values = []
    for step in range(1, len(pool) + 1):
        candidate = getter(pool[(current_index + offset + step - 1) % len(pool)])
        if candidate not in values:
            values.append(candidate)
        if len(values) == count:
            return values
    raise ValueError("Impossible de construire trois distracteurs distincts.")


def _build_options(correct, distractors, seed):
    options = list(distractors[:3])
    answer_index = seed % 4
    options.insert(answer_index, correct)
    return options, "ABCD"[answer_index]


def _basic_questions(category, topics):
    generated = []
    for index, (concept, definition, application, advanced) in enumerate(topics):
        distractors = _pick(topics, index, lambda item: item[0])
        options, answer = _build_options(concept, distractors, index)
        generated.append(
            q(
                category,
                "Basique",
                f"Quel concept correspond le mieux à la description suivante ? {_sentence(definition)}",
                options,
                answer,
                _sentence(f"Il s'agit de {concept} : {definition}"),
            )
        )
    for index, (concept, definition, application, advanced) in enumerate(topics):
        distractors = _pick(topics, index, lambda item: _sentence(item[1]), offset=4)
        options, answer = _build_options(_sentence(definition), distractors, index + 17)
        generated.append(
            q(
                category,
                "Basique",
                f"Quelle affirmation décrit le mieux {concept} ?",
                options,
                answer,
                _sentence(f"{concept} se définit ainsi : {definition}"),
            )
        )
    return generated


def _intermediate_questions(category, topics):
    generated = []
    for index, (concept, definition, application, advanced) in enumerate(topics):
        distractors = _pick(topics, index, lambda item: _sentence(item[2]), offset=2)
        options, answer = _build_options(_sentence(application), distractors, index + 31)
        generated.append(
            q(
                category,
                "Intermédiaire",
                f"Dans quel contexte {concept} est-il le plus pertinent ?",
                options,
                answer,
                _sentence(f"{concept} est particulièrement pertinent lorsqu'il faut {application}"),
            )
        )
    for index, (concept, definition, application, advanced) in enumerate(topics):
        distractors = _pick(topics, index, lambda item: item[0], offset=5)
        options, answer = _build_options(concept, distractors, index + 53)
        generated.append(
            q(
                category,
                "Intermédiaire",
                f"Vous devez {application}. Quelle notion faut-il mobiliser en priorité ?",
                options,
                answer,
                _sentence(f"Le concept à mobiliser est {concept} car il sert à {application}"),
            )
        )
    for index, (concept, definition, application, advanced) in enumerate(topics[:5]):
        correct = _sentence(f"{concept} est surtout utile pour {application}")
        distractors = _pick(topics, index, lambda item: _sentence(f"{item[0]} est surtout utile pour {item[2]}"), offset=7)
        options, answer = _build_options(correct, distractors, index + 79)
        generated.append(
            q(
                category,
                "Intermédiaire",
                f"Quelle est la MEILLEURE réponse au sujet de {concept} ?",
                options,
                answer,
                _sentence(f"La réponse correcte relie {concept} à son usage principal : {application}"),
            )
        )
    return generated


